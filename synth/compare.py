"""Whole dataset vs a simulated 14-day generator run: event density, cluster mix and waveforms (report 07).

Two synthetic datasets over the SAME recorded hours as the real one (342 h, Feb 4-27):
  insample  one generator + timeline fitted on all days (the production model)
  crossfit  days split in two alternating folds; each fold is generated by a model fitted on the OTHER fold
            (no synthetic event comes from a model that saw its day)

Clusters are judged with the C2 definition: aligned correlation (max Pearson over +-1 s shifts, raw crops),
edge if >= 0.9, Louvain, families >= 20 events.
  A1  assignment: each event takes the majority family of its REAL neighbours (corr >= 0.9, self excluded);
      no real neighbour = "isolated". Same rule for real (leave-self-out) and synthetic events.
  A2  novelty: best correlation with any real event (synthetic) vs with any OTHER real event (real).
  A3  new clusters: Louvain on the joint real + synthetic graph. A community of >= 20 events that is
      >= 90 % synthetic would be a cluster the generator invented; >= 90 % real, one it misses.
Density: events per day and per hour of day; family mix overall and by 6-h bin; distributions of morph
features and SNR; 2-D density in embedding space. Waveforms: per family median and p10-p90 band.

    python -m synth.compare          # ~5-10 min (GPU for correlations)
"""
